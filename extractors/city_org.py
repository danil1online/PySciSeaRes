def _normalize_text(text):
    """Нормализует текст для поиска."""
    if not text:
        return ""
    return text.lower().strip()


def _extract_city_from_page1_bottom(text, max_chars=3000):
    """Извлекает город из нижней части первой страницы.

    Формат: "Краснодар 2026" или "г. Краснодар 2026"
    """
    if not text:
        return None

    # Берём последние 3000 символов первой страницы
    search_area = text[-max_chars:] if len(text) > max_chars else text

    # Паттерн: город + год (2020-2030)
    pattern = r'(?:г\.\s*)?([А-ЯЁA-Z][а-яёa-z\s\-]+?)\s+(20[2-3]\d)\s*$'
    match = re.search(pattern, search_area, re.MULTILINE)
    if match:
        city = match.group(1).strip()
        # Убираем лишние слова
        city = re.sub(r'^(кандидат|доктор)\s+диссертация\s+по\s+теме\s+["\u2013\u2014]', '', city, flags=re.IGNORECASE)
        city = re.sub(r'\s*[-—–]\s*.*$', '', city)
        city = city.strip()
        if city and len(city) > 1 and len(city) < 50:
            return city

    # Паттерн: просто город в нижнем колонтитуле
    lines = search_area.split('\n')
    for line in lines[-10:]:
        line = line.strip()
        if not line or len(line) > 100:
            continue
        # Ищем название города
        for city in RUSSIAN_CITIES:
            if city in line:
                # Извлекаем полное название города
                match = re.search(r'[А-ЯЁA-Z][а-яёa-z\- ]+' + re.escape(city), line)
                if match:
                    return match.group(0).strip()

    return None


def _extract_org_from_page2_top(text, max_chars=2000):
    """Извлекает организацию из верхней части второй страницы.

    Формат: "ФГБОУ ВО "МГУ имени Ломоносова"" или "ФГАНБ "НТБ ГАУН"
    """
    if not text:
        return None

    # Вторая страница — это примерно с 3000-5000 символа
    search_area = text[2000:2000 + max_chars] if len(text) > 2000 else text[:max_chars]

    # Паттерн: ФГБОУ ВО, ФГАНБ, ФГБУН, ФGAoPO и т.д.
    patterns = [
        r'(ФГБОУ\s+ВО\s+"[^"]+")',
        r'(ФГАНБ\s+"[^"]+")',
        r'(ФГБУН\s+"[^"]+")',
        r'(ФGAoPO\s+"[^"]+")',
        r'(ФГБУ\s+"[^"]+")',
        r'(ФГАОУ\s+ВО\s+"[^"]+")',
        r'(ФГBOU\s+ВО\s+"[^"]+")',
        r'(Учреждение\s+[^,]+,\s*[^,]+\s+[^,]+)',
        r'(Научно-исследовательский\s+[^,]+)',
        r'(Институт\s+[^,]+,\s*[^,]+)',
        r'(Академия\s+[^,]+,\s*[^,]+)',
        r'(Университет\s+[^,]+,\s*[^,]+)',
        r'(Медицинский\s+[^,]+,\s*[^,]+)',
        r'(Технологический\s+[^,]+,\s*[^,]+)',
        r'(Педагогический\s+[^,]+,\s*[^,]+)',
    ]

    for pattern in patterns:
        match = re.search(pattern, search_area, re.IGNORECASE)
        if match:
            return match.group(1).strip()

    # Альтернативный паттерн: ищем "Научный руководитель" и берём организацию
    sup_pattern = r'Научный\s+руководитель\s*:?\s*([^\n]+)\n\s*([^,]+,\s*[^,]+)'
    match = re.search(sup_pattern, search_area)
    if match:
        org = match.group(2).strip()
        if org and len(org) > 5:
            return org

    return None


def extract_city_and_org(pdf_path):
    """Извлекает город и организацию из автореферата.

    Возвращает: (city, organization_name)
    """
    try:
        with pdfplumber.open(pdf_path) as pdf:
            if len(pdf.pages) < 2:
                return None, None

            # Первая страница — город
            page1_text = pdf.pages[0].extract_text() or ""
            city = _extract_city_from_page1_bottom(page1_text)

            # Вторая страница — организация
            if len(pdf.pages) >= 2:
                page2_text = pdf.pages[1].extract_text() or ""
                org = _extract_org_from_page2_top(page2_text)
            else:
                org = None

            return city, org

    except Exception as e:
        logger.error(f"Error extracting city/org from {pdf_path}: {e}")
        return None, None
